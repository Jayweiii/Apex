#!/usr/bin/env tsx
/**
 * Build src/lib/youtube-catalog.ts from data/videos.json (or the channel RSS).
 *
 * Usage:
 *   npx tsx scripts/import-youtube.ts
 *   npx tsx scripts/import-youtube.ts --rss
 */
import fs from "node:fs";
import path from "node:path";
import { parseTitleHints } from "../src/lib/youtube";

const ROOT = path.resolve(__dirname, "..");
const CHANNEL_ID = "UCedGBL5zO8HMuncMqFUeI0g";
const RSS = `https://www.youtube.com/feeds/videos.xml?channel_id=${CHANNEL_ID}`;

type RawVideo = {
  id: string;
  title: string;
  upload_date_utc?: string;
  uploaded_at_pt?: string;
  duration_s?: number;
  kind?: string;
  track_related?: boolean;
  apex_track_id_suggestion?: string | null;
  best_lap_ms_from_title?: number | null;
  title_lap_precision_ms?: number | null;
  car?: string | null;
};

function normalizeTrackId(suggestion: string | null | undefined, title: string) {
  const hints = parseTitleHints(title);
  if (hints.trackId) return hints.trackId;
  if (!suggestion) return null;
  if (suggestion.includes("buttonwillow")) return "buttonwillow-13cw";
  if (suggestion.includes("streets-of-willow")) return "streets-of-willow-cw";
  if (suggestion.includes("thunderhill")) return "thunderhill-east";
  return suggestion.split(" ")[0] || null;
}

function fromJson(): RawVideo[] {
  const file = path.join(ROOT, "data/videos.json");
  const raw = JSON.parse(fs.readFileSync(file, "utf8")) as {
    videos: RawVideo[];
  };
  return raw.videos.filter(
    (v) =>
      v.track_related ||
      v.kind === "onboard_lap" ||
      v.kind === "track_day_clips",
  );
}

async function fromRss(): Promise<RawVideo[]> {
  const res = await fetch(RSS);
  if (!res.ok) throw new Error(`RSS fetch failed: ${res.status}`);
  const xml = await res.text();
  const entries: RawVideo[] = [];
  const blocks = xml.split("<entry>").slice(1);
  for (const block of blocks) {
    const id = block.match(/<yt:videoId>([^<]+)<\/yt:videoId>/)?.[1];
    const title = block.match(/<title>([^<]+)<\/title>/)?.[1];
    const published = block.match(/<published>([^<]+)<\/published>/)?.[1];
    if (!id || !title) continue;
    const hints = parseTitleHints(title);
    if (!hints.trackId && !/funnies|miata|buttonwillow|thunderhill|willow/i.test(title)) {
      continue;
    }
    entries.push({
      id,
      title,
      upload_date_utc: published?.slice(0, 10),
      kind: hints.lapMs != null ? "onboard_lap" : "track_day_clips",
      track_related: true,
      apex_track_id_suggestion: hints.trackId,
      best_lap_ms_from_title: hints.lapMs ?? null,
      title_lap_precision_ms: hints.lapPrecisionMs,
      car: hints.car,
    });
  }
  return entries;
}

function writeCatalog(videos: RawVideo[]) {
  const entries = videos.map((v) => {
    const hints = parseTitleHints(v.title);
    const trackId = normalizeTrackId(v.apex_track_id_suggestion, v.title);
    return {
      youtubeId: v.id,
      title: v.title,
      uploadedAt: v.upload_date_utc || v.uploaded_at_pt?.slice(0, 10) || "",
      durationSec: v.duration_s ?? 0,
      trackId,
      lapMs: v.best_lap_ms_from_title ?? hints.lapMs ?? null,
      lapPrecisionMs: v.title_lap_precision_ms ?? hints.lapPrecisionMs ?? null,
      kind: v.kind ?? "onboard_lap",
      car: v.car ?? hints.car ?? null,
    };
  });

  const out = `/* Generated by scripts/import-youtube.ts — do not edit by hand. */
import type { YoutubeCatalogEntry } from "./youtube-match";

export const YOUTUBE_CHANNEL = {
  name: "Jayweii",
  handle: "@jayweii5119",
  channelId: "${CHANNEL_ID}",
  url: "https://www.youtube.com/@jayweii5119",
} as const;

export const YOUTUBE_CATALOG: YoutubeCatalogEntry[] = ${JSON.stringify(entries, null, 2)};
`;

  const dest = path.join(ROOT, "src/lib/youtube-catalog.ts");
  fs.writeFileSync(dest, out);
  console.log(`Wrote ${entries.length} track videos → ${dest}`);
}

async function main() {
  const useRss = process.argv.includes("--rss");
  const videos = useRss ? await fromRss() : fromJson();
  writeCatalog(videos);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
