/**
 * Dragy DRG71 VBO format (Jason's real export shape) + Thunderhill West lap split.
 */
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import {
  parseVbo,
  parseVboHhmmss,
  parseVboSessionDate,
  vboCoordToDegrees,
  vboLonToDegrees,
} from "../src/lib/parse-gps-logger";
import { getTrack } from "../src/lib/tracks";

function assert(condition: unknown, message: string): asserts condition {
  if (!condition) throw new Error(message);
}

const root = resolve(import.meta.dirname, "..");

// --- Exact conversions from Jason's sample rows ---
assert(
  Math.abs(vboCoordToDegrees(2372.34294) - 39.539049) < 1e-6,
  "lat minutes → deg",
);
assert(
  Math.abs(vboLonToDegrees(7340.3217) - -122.338695) < 1e-5,
  "lon west-positive minutes → deg",
);

const tod = parseVboHhmmss(161709.6);
assert(tod != null && tod.hours === 16 && tod.minutes === 17, "hhmmss parse");
assert(tod != null && Math.abs(tod.seconds - 9.6) < 1e-9, "hhmmss frac");

const date = parseVboSessionDate(
  "UTC Date Started: 17/10/2026 16:17\nFile created on 17/10/2026 @ 16:17",
);
assert(date?.year === 2026 && date.month === 10 && date.day === 17, "session date");

assert(parseVboHhmmss(235959.9)?.hours === 23, "pre-midnight");
assert(parseVboHhmmss(1.0)?.hours === 0 && parseVboHhmmss(1.0)?.seconds === 1, "00:00:01");
assert(parseVboHhmmss(100.5)?.minutes === 1, "00:01:00.5");

// Jason's first three data rows (idle at Thunderhill West)
const jasonHead = `File created on 17/10/2026 @ 16:17
[header]
satellites
time
latitude
longitude
velocity kmh
heading
height
[channel units]

[comments]
Generated by dragy Lap
Model: dragy DRG71
UTC Date Started: 17/10/2026 16:17
[column names]
sats time lat long velocity heading height
[data]
031 161709.600 +2372.342940 +7340.321700 000.054 331.57 +00103.40
031 161709.700 +2372.342940 +7340.321700 000.086 331.57 +00103.40
031 161709.800 +2372.342940 +7340.321760 000.133 331.57 +00103.40
`;

// Pad idle so we can probe coords via a tiny private path — use fixture for full parse.
const paddedIdle =
  jasonHead +
  Array.from({ length: 22 }, (_, i) => {
    const t = 161709.9 + i * 0.1;
    return `031 ${t.toFixed(3)} +2372.342940 +7340.321700 000.050 331.57 +00103.40`;
  }).join("\n") +
  "\n";

let idleError: string | null = null;
try {
  parseVbo(paddedIdle, {
    startFinish: { lat: 39.53905, lon: -122.3387 },
  });
} catch (err) {
  idleError = err instanceof Error ? err.message : String(err);
}
assert(
  idleError != null && /motion|laps|GPS|samples/i.test(idleError),
  `idle/pit-only fails gracefully (no laps): ${idleError}`,
);

const fixturePath = resolve(
  root,
  "src/lib/fixtures/dragy-drg71-thunderhill-west.vbo",
);
const fixture = readFileSync(fixturePath, "utf8");
assert(/dragy DRG71/i.test(fixture), "fixture mentions DRG71");
assert(/UTC Date Started: 17\/10\/2026/i.test(fixture), "fixture date");
assert(
  fixture.includes("sats time lat long velocity heading height"),
  "column names match Dragy",
);
assert(
  fixture.includes("031 161709.600") || /031\s+161709/.test(fixture),
  "fixture starts near Jason's idle timestamp",
);

const west = getTrack("thunderhill-west");
assert(west != null, "thunderhill-west in catalog");
const sf = { lat: west!.lat, lon: west!.lon };

const parsed = parseVbo(fixture, { startFinish: sf });
assert(parsed.format === "vbo", "format");
assert(parsed.gpsQuality.stream === "VBO", "stream");
assert(parsed.pointCount > 1000, `points ${parsed.pointCount}`);
assert(parsed.startedAtMs != null, "startedAtMs from date + hhmmss");
assert(parsed.sessionDate === "2026-10-17", `sessionDate ${parsed.sessionDate}`);
assert(
  parsed.gpsQuality.satellites != null && parsed.gpsQuality.satellites >= 28,
  `sats ${parsed.gpsQuality.satellites}`,
);
assert(/sats/i.test(parsed.gpsQuality.label), "quality label includes sats");
assert(parsed.laps.length >= 1, `laps via Thunderhill West SF, got ${parsed.laps.length}`);

const startIso = new Date(parsed.startedAtMs!).toISOString();
assert(startIso.startsWith("2026-10-17T16:17:"), `start ${startIso}`);

// First stored points include idle (speed kept low) — full point list before lap normalize
// is not exported; instead check lap starts after motion and is near SF.
const lap0 = parsed.laps[0];
assert(lap0.points[0].lat != null && lap0.points[0].lon != null, "lap gps");
assert(Math.abs(lap0.points[0].lat! - 39.539) < 0.05, `near SF lat ${lap0.points[0].lat}`);
assert(Math.abs(lap0.points[0].lon! + 122.339) < 0.05, `near SF lon ${lap0.points[0].lon}`);

// Minute-boundary: hhmmss must not inflate elapsed (161759.9 → 161800.0 = 0.1s)
const boundaryRows: string[] = [];
for (let i = 0; i < 50; i += 1) {
  const base = 16 * 3600 + 17 * 60 + 59.5 + i * 0.1;
  const h = Math.floor(base / 3600);
  const m = Math.floor((base % 3600) / 60);
  const s = base % 60;
  const hhmmss = h * 10000 + m * 100 + s;
  const a = (i / 50) * Math.PI * 2;
  const lat = 39.539049 + (Math.sin(a) * 500) / 111320;
  const lon =
    -122.338695 +
    ((Math.cos(a) - 1) * 500) /
      (111320 * Math.cos((39.539049 * Math.PI) / 180));
  boundaryRows.push(
    `031 ${hhmmss.toFixed(3)} +${(lat * 60).toFixed(6)} +${(Math.abs(lon) * 60).toFixed(6)} 090.000 90.00 +00103.40`,
  );
}
const boundary = `File created on 17/10/2026 @ 16:17
[comments]
UTC Date Started: 17/10/2026 16:17
[column names]
sats time lat long velocity heading height
[data]
${boundaryRows.join("\n")}
`;
const bParsed = parseVbo(boundary, { startFinish: sf });
// span of relative times should be ~5s (50 * 0.1), not hundreds
const lastT = Math.max(...bParsed.laps.flatMap((l) => l.points.map((p) => p.t)));
assert(lastT < 15, `minute-boundary elapsed ${lastT}s`);

console.log(
  JSON.stringify({
    ok: true,
    jasonLat: vboCoordToDegrees(2372.34294),
    jasonLon: vboLonToDegrees(7340.3217),
    fixturePoints: parsed.pointCount,
    laps: parsed.laps.length,
    sats: parsed.gpsQuality.satellites,
    startedAt: startIso,
    track: west!.id,
    idleGraceful: idleError?.slice(0, 100),
  }),
);
